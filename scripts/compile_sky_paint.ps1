# Compiles selftest/sky_paint.hlsl (vs, ps) into selftest/sky_paint_shader.hpp - the node-replacement self-test's pass
# (docs/internals.md "Self-tests"). Our own shader, so the header is checked in and a normal build needs no dxc.
param(
    [string]$Dxc = $(if ($env:RG_DXC_DIR) { Join-Path $env:RG_DXC_DIR 'dxc.exe' } else { '' })
)
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$src = Join-Path $repoRoot 'selftest\sky_paint.hlsl'
$out = Join-Path $repoRoot 'selftest\sky_paint_shader.hpp'
if (-not $Dxc -or -not (Test-Path $Dxc)) { throw "dxc.exe not found: '$Dxc' (pass -Dxc or set RG_DXC_DIR)" }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// GENERATED by scripts/compile_sky_paint.ps1 from sky_paint.hlsl - do not edit.')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('#include <cstddef>')
[void]$sb.AppendLine('#include <cstdint>')
[void]$sb.AppendLine('namespace selftest::sky_paint {')
foreach ($ep in @(@('vs', 'vs_6_0'), @('ps', 'ps_6_0'))) {
    $tmp = Join-Path $env:TEMP "sky_paint_$($ep[0]).cso"
    $ErrorActionPreference = 'Continue'   # dxc prints warnings on stderr
    & $Dxc -T $ep[1] -E $ep[0] -O3 -Fo $tmp $src 2>&1 | ForEach-Object { "$_" }
    $code = $LASTEXITCODE
    $ErrorActionPreference = 'Stop'
    if ($code -ne 0) { throw "dxc failed for $($ep[0])" }
    $bytes = [IO.File]::ReadAllBytes($tmp)
    $name = 'k' + $ep[0].ToUpper()
    [void]$sb.AppendLine("inline constexpr size_t ${name}Size = $($bytes.Length);")
    [void]$sb.Append("inline constexpr uint8_t ${name}Bytes[${name}Size] = {")
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        if ($i % 20 -eq 0) { [void]$sb.Append("`n    ") }
        [void]$sb.Append(('0x{0:x2}, ' -f $bytes[$i]))
    }
    [void]$sb.AppendLine("`n};")
}
[void]$sb.AppendLine('}  // namespace selftest::sky_paint')
[IO.File]::WriteAllText($out, $sb.ToString())
Write-Host "wrote $out"
