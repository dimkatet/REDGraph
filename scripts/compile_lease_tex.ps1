# Compiles selftest/lease_tex.hlsl (cs) into selftest/lease_tex_shader.hpp - LeaseTexTest's companion (docs/internals.md
# "Self-tests"). Our own shader, so the header is checked in and a normal build needs no dxc.
param(
    [string]$Dxc = $(if ($env:RG_DXC_DIR) { Join-Path $env:RG_DXC_DIR 'dxc.exe' } else { '' })
)
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$src = Join-Path $repoRoot 'selftest\lease_tex.hlsl'
$out = Join-Path $repoRoot 'selftest\lease_tex_shader.hpp'
if (-not $Dxc -or -not (Test-Path $Dxc)) { throw "dxc.exe not found: '$Dxc' (pass -Dxc or set RG_DXC_DIR)" }

$tmp = Join-Path $env:TEMP 'lease_tex_cs.cso'
$ErrorActionPreference = 'Continue'   # dxc prints warnings on stderr
& $Dxc -T cs_6_0 -E main -O3 -Fo $tmp $src 2>&1 | ForEach-Object { "$_" }
$code = $LASTEXITCODE
$ErrorActionPreference = 'Stop'
if ($code -ne 0) { throw 'dxc failed' }
$bytes = [IO.File]::ReadAllBytes($tmp)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// GENERATED by scripts/compile_lease_tex.ps1 from lease_tex.hlsl - do not edit.')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('#include <cstddef>')
[void]$sb.AppendLine('#include <cstdint>')
[void]$sb.AppendLine('namespace selftest::lease_tex {')
[void]$sb.AppendLine("inline constexpr size_t kCSSize = $($bytes.Length);")
[void]$sb.Append('inline constexpr uint8_t kCSBytes[kCSSize] = {')
for ($i = 0; $i -lt $bytes.Length; $i++) {
    if ($i % 20 -eq 0) { [void]$sb.Append("`n    ") }
    [void]$sb.Append(('0x{0:x2}, ' -f $bytes[$i]))
}
[void]$sb.AppendLine("`n};")
[void]$sb.AppendLine('}  // namespace selftest::lease_tex')
[IO.File]::WriteAllText($out, $sb.ToString())
Write-Host "wrote $out"
